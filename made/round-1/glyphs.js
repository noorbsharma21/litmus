/* weight is how much of each cell the dot fills, from a hairline pip to a
   full square; width stretches the cells sideways */
function keel(ch, weight, width, colour){
  var g = KEEL[ch] || KEEL['0'], w = 5 * width, s = '<svg viewBox="0 0 ' + (w + 0.6) + ' 7.6" width="100%" height="100%" aria-label="' + ch + '">';
  var r = 0.12 + weight * 0.38;
  g.forEach(function(row, y){
    for (var x = 0; x < 5; x++) if (row[x] === '1'){
      var cx = x * width + width / 2 + 0.3, cy = y + 0.8;
      if (weight > 0.82) s += '<rect x="' + (cx - width / 2) + '" y="' + (cy - 0.5) + '" width="' + width + '" height="1" fill="' + colour + '"/>';
      else s += '<ellipse cx="' + cx + '" cy="' + cy + '" rx="' + (r * width) + '" ry="' + r + '" fill="' + colour + '"/>';
    }
  });
  return s + '</svg>';
}
